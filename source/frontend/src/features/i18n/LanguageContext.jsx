const LanguageContext = createContext(null);

export function LanguageProvider({children}) {
  const [locale, setLocale] = useState(() => {
    const saved = localStorage.getItem('computer-store-locale');
    return saved === 'en' ? 'en' : 'vi';
  });

  useEffect(() => {
    localStorage.setItem('computer-store-locale', locale);
    document.documentElement.lang = locale;
    document.title = locale === 'en'
      ? 'Computer Store | Technology for every setup'
      : 'Computer Store | Công nghệ cho mọi nhu cầu';
  }, [locale]);

  const value = useMemo(() => ({
    locale,
    setLocale,
    t(key, variables = {}) {
      const template = messages[locale]?.[key] || messages.vi[key] || key;
      return Object.entries(variables).reduce(
        (text, [name, replacement]) => text.replaceAll(`{${name}}`, replacement),
        template
      );
    }
  }), [locale]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error('useLanguage must be used inside LanguageProvider');
  return context;
}
